function initDynamicLists() {
  const container = document.getElementById('objeto-items-container');
  const addBtn = document.getElementById('btn-add-objeto');
  
  // Renders the inputs for service items in the sidebar
  window.renderObjetoInputs = () => {
    container.innerHTML = '';
    
    contractData.clausula1.items.forEach((item, index) => {
      const row = document.createElement('div');
      row.className = 'dynamic-item-row';
      
      const textarea = document.createElement('textarea');
      textarea.value = item;
      textarea.placeholder = `Item de serviço ${String.fromCharCode(97 + index)})`;
      textarea.addEventListener('input', (e) => {
        contractData.clausula1.items[index] = e.target.value;
        updatePreview();
        adjustTextareaHeight(textarea);
      });
      
      const deleteBtn = document.createElement('button');
      deleteBtn.className = 'btn-icon btn-danger';
      deleteBtn.innerHTML = `
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="3 6 5 6 21 6"></polyline><path d="M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"></path><line x1="10" y1="11" x2="10" y2="17"></line><line x1="14" y1="11" x2="14" y2="17"></line></svg>
      `;
      deleteBtn.title = 'Excluir este item';
      deleteBtn.addEventListener('click', () => {
        contractData.clausula1.items.splice(index, 1);
        renderObjetoInputs();
        updatePreview();
      });
      
      row.appendChild(textarea);
      row.appendChild(deleteBtn);
      container.appendChild(row);
      
      // Ajustar altura após anexar ao DOM
      adjustTextareaHeight(textarea);
    });
  };
  
  // Handle adding new items
  addBtn.addEventListener('click', () => {
    contractData.clausula1.items.push('');
    renderObjetoInputs();
    updatePreview();
    
    // Auto scroll to bottom of the accordion content
    setTimeout(() => {
      container.lastElementChild?.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
      container.lastElementChild?.querySelector('textarea')?.focus();
    }, 50);
  });
  
  // Initial render of items
  renderObjetoInputs();
}

